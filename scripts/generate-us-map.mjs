/**
 * Bakes the US map into a static TS source file: src/lib/usMap.ts
 *
 * Why pre-generate instead of loading TopoJSON at runtime?
 *   - The strict CSP in src/proxy.ts allows no external requests, and shipping
 *     the 600KB us-atlas JSON to the browser just to draw an outline is waste.
 *
 * us-atlas states-10m is in raw WGS84 degrees, so it must be projected here.
 * ClientMap projects its lat/lng pins with the same US_ALBERS constants, which
 * is what keeps pins and state outlines in one coordinate space.
 *
 * Run after bumping us-atlas:  node scripts/generate-us-map.mjs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { feature } from "topojson-client"
import { presimplify, simplify } from "topojson-simplify"
import { geoAlbersUsa, geoPath } from "d3-geo"

const SRC = "node_modules/us-atlas/states-10m.json"
const OUT = "src/lib/usMap.ts"

// Albers USA fitted to a 975x610 viewBox. ClientMap re-uses these exact values.
const SCALE = 1300
const TRANSLATE = [487.5, 305]

// Weight below which arc points are dropped, in squared DEGREES (the source
// units). Tuned by eye: removes coastline noise invisible at the ~1100px this
// map ever renders at, while keeping state shapes recognizable.
const SIMPLIFY_WEIGHT = Number(process.env.SIMPLIFY_WEIGHT ?? 0.02)

// FIPS codes for territories geoAlbersUsa doesn't place. Excluded so they don't
// render as stray specks in the corner.
const TERRITORIES = new Set(["60", "66", "69", "72", "78"])

const raw = JSON.parse(readFileSync(SRC, "utf8"))
const topo = simplify(presimplify(raw), SIMPLIFY_WEIGHT)
const states = feature(topo, topo.objects.states)
const nation = feature(topo, topo.objects.nation)

// digits(1) keeps sub-pixel accuracy at 975px wide while roughly halving size.
const projection = geoAlbersUsa().scale(SCALE).translate(TRANSLATE)
const path = geoPath(projection).digits(1)

const statePaths = states.features
  .filter((f) => !TERRITORIES.has(String(f.id)))
  .map((f) => ({ id: f.id, name: f.properties.name, d: path(f) }))
  .filter((s) => s.d)
  .sort((a, b) => a.name.localeCompare(b.name))

const nationPath = path(nation.features[0])

const file = `// AUTO-GENERATED by scripts/generate-us-map.mjs — do not edit by hand.
// Source: us-atlas states-10m.json (pre-projected geoAlbersUsa, 975x610).

export const US_MAP_WIDTH = 975
export const US_MAP_HEIGHT = 610

/** Projection these paths were built with — reuse it to place lat/lng pins. */
export const US_ALBERS = { scale: ${SCALE}, translate: [${TRANSLATE.join(", ")}] as [number, number] }

export const US_NATION_PATH = ${JSON.stringify(nationPath)}

export const US_STATE_PATHS: { id: string; name: string; d: string }[] = ${JSON.stringify(statePaths, null, 2)}
`

writeFileSync(OUT, file)
console.log(`${OUT}: ${statePaths.length} states, ${(file.length / 1024).toFixed(0)} KB`)
